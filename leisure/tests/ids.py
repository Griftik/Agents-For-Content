"""Идентификаторы тестовых пользователей, уникальные на процесс pytest.

Тесты с базой пишут в общую базу `leisure`; фиксированные id сталкивались при двух одновременных прогонах (в том числе чужих).
Сдвиг берётся от pid: 999_000_000 + (pid % 900) * 100 + n, n = 0..99. Все профили этого диапазона чистятся в начале и в конце
сессии (conftest.py), так что остатков упавшего прогона не остаётся."""
import os

BASE = 999_000_000 + (os.getpid() % 900) * 100
RANGE = (BASE, BASE + 100)


def user_id(n: int) -> int:
    assert 0 <= n < 100
    return BASE + n
