def values_text(selected: list[str]) -> str:
    """T-ONB-VALUES; строка «Выбрано» обновляется при каждом нажатии."""
    names = ", ".join(value_label(v) for v in selected)
    if len(selected) == TOP_N:
        tail = f"Выбрано 5 из 5: {escape(names)}. Нажми «Дальше»."
    else:
        tail = f"Выбрано {len(selected)} из 5" + (f": {escape(names)}" if selected else "")
    return ("<b>Шаг 1 из 2 · Что для тебя важно</b>\nВыбери пять ценностей. Подборка пойдёт от них, а не от рубрик афиши. "
            "Кнопки идут группами: познание, люди, тело и чувства, смысл.\n\n" + tail)


