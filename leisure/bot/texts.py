def profile_text(v: Mapping) -> str:
    """T-PROFILE."""
    prm = v["params"]
    top = sorted(VALUES, key=lambda x: -int(v["values"].get(x, 0)))[:TOP_N]
    first = [c for c in ALL_CATS if int(v["interests"].get(c, 2)) == 3]
    off = [c for c in ALL_CATS if int(v["interests"].get(c, 2)) == 0]
    budget = int(prm.get("budget") or 0)
    learned = v.get("learned_text") or ""
    if not learned or learned.startswith("пока мало"):
        learned = LEARNED_EMPTY
    lines = ["<b>Твой профиль</b>", "", "<b>Главные ценности</b>", escape(", ".join(top)), "", "<b>Направления</b>",
             f"В первую очередь: {escape(', '.join(first)) if first else 'пока нет'}",
             f"Не показываю: {escape(', '.join(off)) if off else 'ничего'}", "", "<b>Параметры</b>",
             f"Время: {escape(', '.join(prm.get('times') or ['день', 'вечер']))}",
             f"Бюджет: {escape(budget_label(budget))}",
             f"Эстетика: {'важна' if prm.get('aesthetics') else 'не принципиальна'}"]
    if prm.get("company") == "с детьми" or prm.get("kids"):
        lines.append("С детьми: да")
    lines += ["", "<b>Что я узнал о тебе</b>", escape(learned)]
    return "\n".join(lines)
