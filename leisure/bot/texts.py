def all_text(interests: Mapping[str, int]) -> str:
    """T-ONB-ALL: списки по уровням (полные имена направлений)."""
    def lst(lvl: int, empty: str) -> str:
        names = [c for c in ALL_CATS if int(interests.get(c, 2)) == lvl]
        return escape(", ".join(names)) if names else empty

    return ("<b>Все направления</b>\nВыбери, как отметить, и нажимай на направления.\n\n"
            f"В первую очередь: {lst(3, 'пока нет')}\nИнтересно: {lst(2, 'ничего')}\nИногда: {lst(1, 'ничего')}\n"
            f"Не показываю: {lst(0, 'ничего')}\n\n✓✓ в первую очередь · ✓ интересно · без значка иногда · — не показывать")


def saved_text(top: list[str], interests: Mapping[str, int], budget: int = 0) -> str:
    """T-ONB-SAVED."""
    first = [c for c in ALL_CATS if int(interests.get(c, 2)) == 3]
